# Puts a plugged-in Tactrix OpenPort 2.0 onto Microsoft's own USB serial driver (usbser.sys), so it
# shows up as a COM port that SubieScope can use. Only needed when Windows did not give the cable a
# COM port by itself. "Install OpenPort driver.cmd" next to this file runs it; README.txt says more.
#
# Windows asks for administrator rights first, and then this script asks once more before it changes
# anything. The install itself is done by wdi-simple.exe (libwdi, the library the Zadig tool is built
# on): it writes a small driver package that points the cable at usbser.sys, signs it with a one-off
# certificate that it adds to this PC's trusted certificates (as Zadig does; the certificate's private
# key is thrown away at once, so it can vouch for nothing else), and installs it.
#
# It installs ONLY Microsoft's in-box usbser.sys. It does not install Tactrix's driver or touch the
# cable's firmware, so it is safe for a replica cable. Do NOT install Tactrix's driver or EcuFlash on a
# PC with a replica, and do not plug a replica into a PC that has them: they rewrite the cable's
# firmware and break it for good.
#
# NOTE: this has not been tried on real hardware yet. README.txt also explains how to do the same by
# hand in Device Manager.
$ErrorActionPreference = 'Stop'

# Re-launch with administrator rights if we do not have them. The new window stays open (-NoExit), so
# the messages below can be read; that is also why the rest of this script ends with return, not exit.
$admin = ([Security.Principal.WindowsPrincipal][Security.Principal.WindowsIdentity]::GetCurrent()
         ).IsInRole([Security.Principal.WindowsBuiltInRole]::Administrator)
if (-not $admin) {
    "Asking for administrator rights..."
    try {
        Start-Process powershell -Verb RunAs -ArgumentList @(
            '-NoProfile', '-ExecutionPolicy', 'Bypass', '-NoExit', '-File', "`"$PSCommandPath`"")
    } catch {
        Write-Warning "Windows did not give administrator rights, so nothing was changed."
        exit 1
    }
    "The rest happens in the new window that just opened (it may be behind this one)."
    exit 0
}

$wdi = Join-Path $PSScriptRoot 'wdi-simple.exe'
if (-not (Test-Path $wdi)) { throw "wdi-simple.exe was not found next to this script." }

# wdi-simple carries the installer for PCs with an Intel or AMD processor only (x64).
if ((Get-CimInstance Win32_Processor | Select-Object -First 1).Architecture -eq 12) {
    Write-Warning "This PC has an Arm processor, and this helper only works on a PC with an Intel or AMD one."
    Write-Warning "Do it by hand instead: README.txt next to this script explains how, in Device Manager."
    return
}

# Which OpenPort is plugged in? CC4C is the composite form (bind interface 0); CC4D is the plain one.
$ids = @(Get-PnpDevice -PresentOnly -ErrorAction SilentlyContinue |
    Where-Object InstanceId -match 'VID_0403&PID_CC4[CD]' | ForEach-Object InstanceId)
if ($ids.Count -eq 0) {
    Write-Warning "No Tactrix OpenPort 2.0 is plugged in. Plug the cable into this PC and run this again."
    Write-Warning "(If Windows already shows the cable as a COM port, you do not need this at all.)"
    return
}
if ($ids -match 'PID_CC4C') {
    $devPid, $mi, $hardwareID = '0xCC4C', '0x00', 'VID_0403&PID_CC4C&MI_00'
} else {
    $devPid, $mi, $hardwareID = '0xCC4D', $null, 'VID_0403&PID_CC4D'
}

""
"Found a Tactrix OpenPort 2.0 (USB\$hardwareID)."
"This puts it on Windows' own USB serial driver (usbser.sys), so that it gets a COM port. It installs"
"nothing of Tactrix's and does not touch the cable's firmware. It can take up to a minute."
$answer = Read-Host "Type Y and press Enter to go ahead, or just press Enter to stop"
if ($answer -notmatch '^\s*y') {
    "Stopped. Nothing was changed."
    return
}

# libwdi writes the driver package into a folder, which goes once the install is done (Windows keeps
# its own copy). The folder is under Windows' Temp, not the user's: wdi-simple gets the path as 8-bit
# text and libwdi reads it as UTF-8, so a user name with accents or non-English letters would break it.
$work = Join-Path $env:SystemRoot 'Temp\subiescope-openport-driver'
if (Test-Path $work) { Remove-Item -Recurse -Force $work }
$wdiArgs = @('-n', 'Tactrix OpenPort 2.0 (USB Serial)', '-m', 'Tactrix',
             '-v', '0x0403', '-p', $devPid, '-t', '3', '-f', 'openport_cdc.inf', '-d', $work)
if ($mi) { $wdiArgs += @('-i', $mi) }
& $wdi @wdiArgs
$code = $LASTEXITCODE
Remove-Item -Recurse -Force $work -ErrorAction SilentlyContinue

if ($code -ne 0) {
    # libwdi trusts its one-off certificate before it installs. The driver it was made for did not go
    # in, so take the certificate away again.
    Get-ChildItem Cert:\LocalMachine\Root, Cert:\LocalMachine\TrustedPublisher |
        Where-Object Subject -eq "CN=USB\$hardwareID (libwdi autogenerated)" | Remove-Item
    Write-Warning "The driver was not installed (libwdi error $code). Its certificate was taken away again."
    Write-Warning "README.txt next to this script explains how to do it by hand in Device Manager."
    return
}

""
"Done. Unplug the cable and plug it back in. Device Manager should then show it under Ports (COM & LPT)"
"as `"Tactrix OpenPort 2.0 (USB Serial)`" with a COM number. In SubieScope, turn on `"Tactrix OpenPort"
"2.0 cable`" in Settings and pick that port."
